// Generates themes/density/<preset>.css from the presets: the "compact" and "comfortable" density scale the
// spacing tokens (paddings, gaps of lists/menus, sizes of icon-only and paginator buttons) of each preset.
// Rerun after changing the presets: node build/scripts/themes/generate-density.mjs (--check fails if a file is not up to date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const cssDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'themes');
const outDir = path.join(cssDir, 'density');
// "normal" restores the values of the preset inside a compact or comfortable area
const DENSITIES = { normal: 1, compact: 0.75, comfortable: 1.25 };

// spacing tokens; sm/lg variants keep their size, small elements (badges, chips, ...) are not part of the density
const SCALED = /^--p-[a-z0-9-]*-(padding(-x|-y)?|nav-button-(width|height)|icon-only-width|option-gap|item-gap)$/;
const EXCLUDED = /^--p-(badge|overlaybadge|tag|chip|tooltip|avatar|toggleswitch|slider|progressbar|skeleton|knob|rating|checkbox|radiobutton|scrolltop|speeddial|message|toast|growl|inputotp|iconfield)-|-(sm|lg|xl)-/;

const scale = (value, factor) => factor === 1 ? value : value.replace(/(-?\d*\.?\d+)(rem|px|em)\b/g, (_, n, unit) => {
    const v = parseFloat(n) * factor;
    return `${unit === 'px' ? Math.round(v) : Math.round(v * 1000) / 1000}${unit}`;
});

const presets = fs.readdirSync(path.join(cssDir, 'presets')).filter((f) => f.endsWith('.css')).map((f) => f.slice(0, -4)).sort();
fs.mkdirSync(outDir, { recursive: true });
const orphans = fs.readdirSync(outDir).filter((f) => f.endsWith('.css') && !presets.includes(f.slice(0, -4)));
if (orphans.length) {
    console.error(`density/ has files without a preset, delete them: ${orphans.join(' ')}`);
    process.exit(1);
}
for (const preset of presets) {
    const css = fs.readFileSync(path.join(cssDir, 'presets', `${preset}.css`), 'utf8').replace(/\r\n/g, '\n');
    const tokens = [...css.matchAll(/^\s+(--p-[a-z0-9-]+):\s*(.+);$/gm)]
        .filter(([, n, v]) => SCALED.test(n) && !EXCLUDED.test(n) && /\d(rem|px|em)\b/.test(v) && !v.includes('var('))
        .map(([, n, v]) => [n, v]);
    let out = `/*\n * Density of the ${preset} preset (generated by build/scripts/themes/generate-density.mjs, do not edit).\n`
        + ' * <html data-p-density="compact|comfortable"> or on any other element, e.g. <div data-p-density="compact">; "normal" restores the preset\n */\n'
        + '@layer primefaces.tokens {\n';
    for (const [density, factor] of Object.entries(DENSITIES)) {
        out += `    [data-p-density="${density}"] {\n` + tokens.map(([n, v]) => `        ${n}: ${scale(v, factor)};\n`).join('') + '    }\n';
    }
    out += '}\n';
    const file = path.join(outDir, `${preset}.css`);
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== out) {
            console.error(`density/${preset}.css is not up to date, run node build/scripts/themes/generate-density.mjs`);
            process.exit(1);
        }
        continue;
    }
    fs.writeFileSync(file, out);
    console.log(`density/${preset}.css: ${tokens.length} tokens`);
}
