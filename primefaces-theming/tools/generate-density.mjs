// Generates src/main/css/density/<preset>.css from the presets: the "compact" and "comfortable" density scale the
// spacing tokens (paddings, gaps of lists/menus, sizes of icon-only and paginator buttons) of each preset.
// Rerun after changing the presets: node tools/generate-density.mjs (--check fails if a file is not up to date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const cssDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'main', 'css');
const outDir = path.join(cssDir, 'density');
const DENSITIES = { compact: 0.75, comfortable: 1.25 };

// spacing tokens; sm/lg variants keep their size, small elements (badges, chips, ...) are not part of the density
const SCALED = /^--p-[a-z0-9-]*-(padding(-x|-y)?|nav-button-(width|height)|icon-only-width|option-gap|item-gap)$/;
const EXCLUDED = /^--p-(badge|overlaybadge|tag|chip|tooltip|avatar|toggleswitch|slider|progressbar|skeleton|knob|rating|checkbox|radiobutton|scrolltop|speeddial|message|toast|growl|inputotp|iconfield)-|-(sm|lg|xl)-/;

const scale = (value, factor) => value.replace(/(-?\d*\.?\d+)(rem|px|em)\b/g, (_, n, unit) => {
    const v = parseFloat(n) * factor;
    return `${unit === 'px' ? Math.round(v) : Math.round(v * 1000) / 1000}${unit}`;
});

fs.mkdirSync(outDir, { recursive: true });
for (const preset of ['aura', 'lara', 'nora']) {
    const css = fs.readFileSync(path.join(cssDir, 'presets', `${preset}.css`), 'utf8').replace(/\r\n/g, '\n');
    const tokens = [...css.matchAll(/^\s+(--p-[a-z0-9-]+):\s*(.+);$/gm)]
        .filter(([, n, v]) => SCALED.test(n) && !EXCLUDED.test(n) && /\d(rem|px|em)\b/.test(v) && !v.includes('var('))
        .map(([, n, v]) => [n, v]);
    let out = `/*\n * Density of the ${preset} preset (generated by tools/generate-density.mjs, do not edit).\n`
        + ' * <html data-p-density="compact|comfortable">, or on an element that is also a scope: <div data-p-scope data-p-density="compact">\n */\n'
        + '@layer primefaces.tokens {\n';
    for (const [density, factor] of Object.entries(DENSITIES)) {
        out += `    [data-p-density="${density}"] {\n` + tokens.map(([n, v]) => `        ${n}: ${scale(v, factor)};\n`).join('') + '    }\n';
    }
    out += '}\n';
    const file = path.join(outDir, `${preset}.css`);
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== out) {
            console.error(`density/${preset}.css is not up to date, run node tools/generate-density.mjs`);
            process.exit(1);
        }
        continue;
    }
    fs.writeFileSync(file, out);
    console.log(`density/${preset}.css: ${tokens.length} tokens`);
}
